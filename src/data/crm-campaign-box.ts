/**
 * Business-in-a-box campaign pack — drip, education, follow-up, and ops workflows
 * that CROs typically have to invent from scratch. None of these lock a firm out
 * of the product; they encourage packet signatures and portal activity.
 */
import type { WorkflowDefinition } from './crm-campaign-library';

const email = (
  delayHours: number,
  subject: string,
  bodyTemplate: string,
  lane: WorkflowDefinition['lane'] = 'marketing',
): WorkflowDefinition['steps'][number] => ({
  delayHours, action: 'email', lane, subject, bodyTemplate,
});

const sms = (
  delayHours: number,
  bodyTemplate: string,
  lane: WorkflowDefinition['lane'] = 'transactional',
): WorkflowDefinition['steps'][number] => ({
  delayHours, action: 'sms', lane, bodyTemplate,
});

const task = (delayHours: number, taskTitle: string, taskPriority = 'P2'): WorkflowDefinition['steps'][number] => ({
  delayHours, action: 'task', taskTitle, taskPriority,
});

